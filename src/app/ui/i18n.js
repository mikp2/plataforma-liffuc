const I18nContext = createContext(null);
const languageStorageKey = "liffuc-language";

function getLanguageSnapshot() {
  const savedLanguage = window.localStorage.getItem(languageStorageKey);
  return savedLanguage && Object.hasOwn(languages, savedLanguage) ? savedLanguage : "es";
}

function subscribeToLanguageChange(callback) {
  window.addEventListener("storage", callback);
  document.addEventListener("liffuc-language-change", callback);
  return () => {
    window.removeEventListener("storage", callback);
    document.removeEventListener("liffuc-language-change", callback);
  };
}

export function LanguageProvider({ children }) {
  const language = useSyncExternalStore(
    subscribeToLanguageChange,
    getLanguageSnapshot,
    () => "es",
  );
  const setLanguage = useCallback((nextLanguage) => {
    if (!Object.hasOwn(languages, nextLanguage)) {
      throw new Error(`Unsupported language: ${nextLanguage}`);
    }
    window.localStorage.setItem(languageStorageKey, nextLanguage);
    document.dispatchEvent(new CustomEvent("liffuc-language-change", { detail: { language: nextLanguage } }));
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    locale: languages[language].locale,
    setLanguage,
    t: (key) => translations[language]?.[key] || key,
  }), [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within LanguageProvider.");
  return context;
}
